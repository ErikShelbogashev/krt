package krt.domain.trace

import krt.domain.scene.model.FractalKind
import krt.domain.scene.model.PatternKind

/**
 * The GPU path tracer's source (ADR 0009): a pure transformation. The shader lives in parts under
 * `src/main/resources`, each beside the package of the Kotlin it mirrors (`krt/domain/scene/model/microfacets.sksl`
 * next to `Microfacets`), and is joined in [PARTS]' order. The constants the shader shares with the Kotlin packing,
 * record sizes and codes of primitives, materials and patterns, are not written in it: [constants] generates them
 * from [GpuScenePacking], [Bvh] and [PatternKind], so the two cannot drift apart.
 */
object GpuShaderSource {

    val DISPLAY_PARTS = listOf("/krt/domain/render/gpu_radiance.sksl", "/krt/domain/render/window_display.sksl")

    fun windowDisplay(read: (String) -> String): String = DISPLAY_PARTS.joinToString("\n", transform = read)

    /** The parts of the shader, as resource paths, in the order they are joined; the constants go after the first. */
    val PARTS = listOf(
        "/krt/domain/render/gpu_frame.sksl",
        "/krt/domain/render/gpu_radiance.sksl",
        "/krt/domain/trace/gpu_scene.sksl",
        "/krt/platform/math/random.sksl",
        "/krt/domain/scene/model/sphere.sksl",
        "/krt/domain/scene/model/dielectric.sksl",
        "/krt/domain/scene/model/spectrum.sksl",
        "/krt/domain/scene/model/thin_film.sksl",
        "/krt/domain/scene/model/sky.sksl",
        "/krt/domain/scene/model/triangle.sksl",
        "/krt/domain/scene/model/fractal.sksl",
        "/krt/domain/trace/trace_scene.sksl",
        "/krt/domain/scene/model/microfacets.sksl",
        "/krt/domain/scene/model/conductor.sksl",
        "/krt/domain/scene/model/sheen.sksl",
        "/krt/domain/scene/model/noise.sksl",
        "/krt/domain/scene/model/pattern.sksl",
        "/krt/domain/scene/model/emissive.sksl",
        "/krt/domain/trace/bvh.sksl",
        "/krt/domain/scene/model/medium.sksl",
        "/krt/domain/trace/lights.sksl",
        "/krt/domain/trace/path_tracing.sksl",
        "/krt/domain/render/path_tracer.sksl",
    )

    /** The whole shader: the parts as [read] gives their text, the generated constants after the first. */
    fun assemble(read: (String) -> String): String {
        val parts = PARTS.map(read)
        return (listOf(parts.first(), constants()) + parts.drop(1)).joinToString("\n")
    }

    /** The constants of the scene texture's layout and codes, as SkSL declarations. */
    fun constants(): String = buildString {
        appendLine("// Generated by GpuShaderSource from the Kotlin packing: layout and codes of the scene texture.")
        appendLine("const int LEAF_SIZE = ${Bvh.LEAF_SIZE};")
        appendLine("const int MAX_PATH_CROSSINGS = ${PathTracing.MAX_PATH_CROSSINGS};")
        appendLine("const int MAX_SHADOW_CROSSINGS = ${PathTracing.MAX_CROSSINGS};")
        FractalKind.entries.forEach { appendLine("const int ${it.name}_ITERATIONS = ${it.gpuIterations};") }
        number("TEXTURE_WIDTH", GpuScenePacking.TEXTURE_WIDTH)
        number("RANGE", GpuScenePacking.RANGE)
        number("NODE_VALUES", GpuScenePacking.NODE_VALUES)
        number("PRIMITIVE_VALUES", GpuScenePacking.PRIMITIVE_VALUES)
        number("MEDIUM_VALUES", GpuScenePacking.MEDIUM_VALUES)
        number("LIGHT_VALUES", GpuScenePacking.LIGHT_VALUES)
        number("MEMBER_VALUES", GpuScenePacking.MEMBER_VALUES)
        number("NORMAL_VALUES", GpuScenePacking.NORMAL_VALUES)
        number("MATERIAL_VALUES", GpuScenePacking.MATERIAL_VALUES)
        PRIMITIVES.forEach { (name, code) -> number(name, code) }
        MATERIALS.forEach { (name, code) -> number(name, code) }
        PatternKind.entries.forEach { number(it.name, it.ordinal) }
    }

    private fun StringBuilder.number(name: String, value: Number) =
        appendLine("const float $name = ${value.toDouble()};")

    private val PRIMITIVES = listOf(
        "SPHERE" to GpuScenePacking.SPHERE,
        "TRIANGLE" to GpuScenePacking.TRIANGLE,
        "FRACTAL" to GpuScenePacking.FRACTAL,
    )

    private val MATERIALS = listOf(
        "LAMBERT" to GpuScenePacking.LAMBERT,
        "METAL" to GpuScenePacking.METAL,
        "DIELECTRIC" to GpuScenePacking.DIELECTRIC,
        "EMISSIVE" to GpuScenePacking.EMISSIVE,
        "PLASTIC" to GpuScenePacking.PLASTIC,
        "CHECKER" to GpuScenePacking.CHECKER,
        "INTERFACE" to GpuScenePacking.INTERFACE,
        "BUBBLE" to GpuScenePacking.BUBBLE,
        "IRIDESCENT" to GpuScenePacking.IRIDESCENT,
        "CONDUCTOR" to GpuScenePacking.CONDUCTOR,
        "VELVET" to GpuScenePacking.VELVET,
        "PATTERNED" to GpuScenePacking.PATTERNED,
        "GLOWING" to GpuScenePacking.GLOWING,
    )
}
